/**
* miradorViewer.php - Initialises and handles the Heurist Mirador viewer.
*
* It uses the customised Mirador viewer from external/mirador3 when available.
* If the customised viewer is missing, it falls back to the latest Mirador
* distribution from unpkg.com.
*
* For annotations, the Heurist database must define either RT_IIIF_ANNOTATION
* or RT_ANNOTATION. The viewer exposes endpointURL, manifestUrl and
* sourceRecordId to the Mirador integration code.
*
* Allowed public request parameters
* ---------------------------------
*
* db
*   Required. Heurist database name.
*
* manifest
*     Explicit IIIF Manifest identifier: either a managed RT_IIIF_MANIFEST
*     record ID or a registered Manifest file obfuscated ID.
* 
*     miradorViewer.php always opens this through the Heurist IIIF API:
*         /api/{db}/iiif/manifest/{manifest}?omit_annotation_pages=1
* 
*     For managed RT_IIIF_MANIFEST records, this returns the fully managed
*     Heurist Manifest.
* 
*     For registered Manifest files without a managed RT_IIIF_MANIFEST record,
*     DbIiifManifest::getManifestFileJson() controls the behaviour:
*         - v2 source Manifests are returned as original source Manifests;
*         - v3 source Manifests are returned as Heurist annotation-overlay
*           Manifests, with original annotation pages stripped/suppressed.
* 
*     To view the untouched original uploaded Manifest file, use the Heurist
*     file URL directly:
*         ?db={db}&file={manifestFileID} 
* 
*
* id
*   Record ID or registered file/url obfuscated ID.
*
*   If id is a positive integer, it is treated as a Heurist record ID.
*   The dynamic manifest is generated by record_output.php:
*       /hserv/controller/record_output.php?db={db}&format=iiif&q=ids:{id}
*
*   Exception: if the record is RT_IIIF_ANNOTATION, the viewer resolves the
*   annotation's parent media/manifest record and Canvas URI first. This special
*   behaviour is intentionally kept here, because a dynamic export of the
*   annotation record itself produces an empty manifest.
*
*   If id is not a positive integer, it is treated as an uploaded file
*   obfuscated ID. The dynamic manifest is generated by record_output.php:
*       /hserv/controller/record_output.php?db={db}&format=iiif&iiif_image={id}
*
* q
*   Heurist query used to generate a dynamic manifest through record_output.php:
*       /hserv/controller/record_output.php?db={db}&format=iiif&q={q}
*
* url
*   Direct Manifest URL. This is passed to Mirador unchanged, except for HTML
*   escaping at output time. It is useful for external manifests or diagnostics.
*
* preparedID
*   Short reference to prepared export/feed parameters created by exportMenu.js
*   for long queries or large ID lists. The parameters are restored and passed
*   to record_output.php with format=iiif.
*
* canvasUri
*   Optional Canvas URI to select when Mirador opens. This is viewer-only and is
*   not forwarded to record_output.php.
*
* annotation_scope / anno_scope
*   Optional annotation lookup scope for the internal Mirador viewer:
*       canvas   - show annotations targeting the same Canvas URL; default.
*       manifest - show annotations linked to the current managed Manifest
*                  context, when a Manifest record ID is known.
*
* Deprecated public parameters
* ----------------------------
* recID, iiif and iiif_image are intentionally no longer part of the public
* miradorViewer.php interface. Use id or manifest instead. iiif_image remains
* an internal parameter passed from this viewer to record_output.php.
*
