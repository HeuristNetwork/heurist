$dbname = @$_REQUEST['db'];
$idParam = trim((string)($_REQUEST['id'] ?? ''));
$manifestParam = trim((string)($_REQUEST['manifest'] ?? ''));
$directManifestUrl = trim((string)($_REQUEST['url'] ?? ''));

$manifestRecID = 0;        // Known only for managed Manifest record context.
$sourceRecordId = 0;       // Passed to the annotation client as window.sourceRecordId.
$canvasUri = null;         // Initial Canvas selection for Mirador.
$baseUrl = null;
$system = null;
$preparedParams = null;
$resolvedIiifImageID = null; // Internal record_output.php iiif_image parameter.
$hideThumbs = false;

// Annotation lookup scope for the internal Mirador viewer.
// canvas   - show all annotations that target the same Canvas URL.
// manifest - show only annotations imported/created in the current Manifest context.
$annotationScope = strtolower(trim((string)(@$_REQUEST['annotation_scope'] ?: @$_REQUEST['anno_scope'] ?: 'canvas')));
if(!in_array($annotationScope, array('canvas', 'manifest'), true)){
    $annotationScope = 'canvas';
}

$validDatabaseName = is_string($dbname) && $dbname!=='' && !preg_match('[\W]', $dbname);
$idIsRecordID = preg_match('/^[1-9][0-9]*$/', $idParam) === 1;

// System initialisation is needed only for prepared parameters and numeric id
// resolution. Non-numeric id, manifest, q and url can be converted to a manifest
// URL without touching the database here.
$needsSystem = $validDatabaseName && (
    array_key_exists('preparedID', $_REQUEST) ||
    $idIsRecordID
);

if($needsSystem){

    require_once dirname(__FILE__).'/../../../autoload.php';

    $system = new hserv\System();
    if( ! $system->init($dbname, true, false) ){
        $system->errorExitApi(); // exits
    }

    $baseUrl = defined('HEURIST_BASE_URL') ? HEURIST_BASE_URL : null;

    if(array_key_exists('preparedID', $_REQUEST)){

        // preparedID is produced by exportMenu.js when q/rules/ids are too long
        // for a normal URL. Restore the prepared export-feed/export parameters
        // and later send them to record_output.php as a dynamic IIIF manifest.
        $params = $_REQUEST;
        $preferredType = array_key_exists('file', $params) ? 'export' : 'export-feed';
        $fallbackType = $preferredType === 'export' ? 'export-feed' : 'export';

        if(!\hserv\utilities\USystem::getPreparedParameters($system, $preferredType, $params)){
            $params = $_REQUEST;
            if(!\hserv\utilities\USystem::getPreparedParameters($system, $fallbackType, $params)){
                $system->errorExitApi(null, null, false);
            }
        }

        unset($params['preparedID'], $params['preparedMode'], $params['preparedType']);
        $params['db'] = $dbname;
        $_REQUEST = array_merge($_REQUEST, $params);
        $preparedParams = $params;
    }
}

if($system!=null && $idIsRecordID){

    // Numeric id normally means a record whose media should be exported by
    // record_output.php. However, annotation records need special handling:
    // exporting the annotation record itself produces an empty manifest, so the
    // viewer resolves the parent media/manifest record and target Canvas here.
    $sourceRecordId = intval($idParam);

    if($system->defineConstant('RT_IIIF_ANNOTATION')){
        $system->defineConstant('RT_IIIF_MANIFEST');
        $system->defineConstant('DT_URL');

        $res = recordSearchByID($system, $sourceRecordId, false, 'rec_ID,rec_RecTypeID');
        $mysqli = $system->getMysqli();

        if(is_array($res) && intval(@$res['rec_RecTypeID']) === RT_IIIF_ANNOTATION){

            // Annotation record case:
            //   1. Find the parent record that carries the registered IIIF
            //      media/manifest file.
            //   2. Read DT_URL from the annotation as the Canvas URI.
            //   3. Generate the Mirador manifest from the parent file rather
            //      than from the annotation record itself.
            $query = 'SELECT dtl_RecID, ulf_ObfuscatedFileID '
                .' FROM recLinks, recDetails, recUploadedFiles '
                .' WHERE rl_SourceID='.$sourceRecordId
                .' AND dtl_RecID=rl_TargetID '
                .' AND dtl_UploadedFileID=ulf_ID '
                .' AND (ulf_PreferredSource="iiif" OR ulf_OrigFileName="'.ULF_IIIF.'")';

            $row = mysql__select_row($mysqli, $query);

            if($row!=null && defined('DT_URL')){

                $query = 'SELECT dtl_Value FROM recDetails WHERE '
                    .' dtl_RecID='.$sourceRecordId.' AND dtl_DetailTypeID='.DT_URL;
                $canvasUri = mysql__select_value($mysqli, $query);

                $sourceRecordId = intval($row[0]);
                $resolvedIiifImageID = (string)$row[1];

            }else{
                exit('Unable to resolve parent IIIF media or manifest for annotation record id='.$idParam);
            }

        }else{

            // Normal record case:
            // Keep the record ID as the dynamic manifest source. If annotations
            // already target one of its canvases, select the most frequently used
            // Canvas URI when Mirador opens.
            if(defined('RT_IIIF_MANIFEST') && is_array($res)
                && intval(@$res['rec_RecTypeID']) === RT_IIIF_MANIFEST){
                $manifestRecID = $sourceRecordId;
            }

            if(defined('DT_URL')){
                $query = 'SELECT dtl_Value, count(*) as cnt FROM recDetails, recLinks, Records '
                    .' WHERE rl_TargetID='.$sourceRecordId
                    .' AND rec_ID=rl_SourceID AND rec_RecTypeID='.RT_IIIF_ANNOTATION
                    .' AND dtl_RecID=rec_ID '
                    .' AND dtl_DetailTypeID='.DT_URL
                    .' GROUP BY dtl_Value ORDER BY cnt DESC';

                $row = mysql__select_row($mysqli, $query);
                if(is_array($row) && @$row[0]!=null){
                    $canvasUri = $row[0];
                }
            }
        }
    }
}

if($baseUrl==null){

    $https = (isset($_SERVER['HTTPS']) &&
                    ($_SERVER['HTTPS'] == 'on' || $_SERVER['HTTPS'] == 1) ||
                    isset($_SERVER['HTTP_X_FORWARDED_PROTO']) &&
                    $_SERVER['HTTP_X_FORWARDED_PROTO'] == 'https');

    $baseUrl = ($https ? 'https://' : 'http://').
            (!empty($_SERVER['REMOTE_USER']) ? $_SERVER['REMOTE_USER'].'@' : '').
            (isset($_SERVER['HTTP_HOST']) ? $_SERVER['HTTP_HOST'] : ($_SERVER['SERVER_NAME'].
            ($https && $_SERVER['SERVER_PORT'] === 443 ||
            $_SERVER['SERVER_PORT'] === 80 ? '' : ':'.$_SERVER['SERVER_PORT'])));

    $path = trim($_SERVER['SCRIPT_NAME']);
    $path = trim($path, '/');
    $parts = explode('/', $path);
    $version = $parts[0] ?? '';
    if(!($version === 'heurist'
            || preg_match('/^h7-[A-Za-z0-9_-]+$/', $version) === 1)){
        $version = 'h7-alpha';
    }

    $baseUrl = $baseUrl.'/'.$version.'/';
}

function appendQueryParam($url, $name, $value){
    if($name==='' || strpos($url, $name.'=')!==false){
        return $url;
    }
    $sep = (strpos($url, '?')===false) ? '?' : '&';
    return $url.$sep.rawurlencode($name).'='.rawurlencode((string)$value);
}

function buildRecordOutputIiifUrl($baseUrl, $params){
    $params['format'] = 'iiif';
    return $baseUrl.'hserv/controller/record_output.php?'.http_build_query($params);
}

if($directManifestUrl !== ''){

    // Direct manifest URL case:
    // Use the caller-supplied manifest URL unchanged. This supports external
    // manifests and diagnostic URLs that should not be normalised by Heurist.
    $url = $directManifestUrl;

}elseif($manifestParam !== ''){

    // Explicit manifest case:
    // The caller is asking for a known IIIF Manifest identity. Use the canonical
    // Heurist IIIF API route instead of the dynamic recordset exporter.
    $url = $baseUrl.'api/'.rawurlencode($dbname)
        .'/iiif/manifest/'.rawurlencode($manifestParam)
        .'?omit_annotation_pages=1';
        

    if(preg_match('/^[1-9][0-9]*$/', $manifestParam)){
        $manifestRecID = intval($manifestParam);
        $sourceRecordId = $manifestRecID;
    }

}elseif(is_array($preparedParams)){

    // Prepared query/resultset case:
    // exportMenu.js stores large q/rules/ids values under preparedID. Restore
    // those parameters and pass them to record_output.php, which knows how to
    // generate a dynamic IIIF manifest from a resultset.
    unset($preparedParams['canvasUri'], $preparedParams['annotation_scope'], $preparedParams['anno_scope']);
    unset($preparedParams['id'], $preparedParams['manifest'], $preparedParams['url']);
    unset($preparedParams['recID'], $preparedParams['iiif'], $preparedParams['iiif_image']);

    $preparedParams['db'] = $dbname;
    $url = buildRecordOutputIiifUrl($baseUrl, $preparedParams);

}elseif($resolvedIiifImageID !== null && $resolvedIiifImageID !== ''){

    // Annotation record resolution case:
    // id was an RT_IIIF_ANNOTATION record. Generate the manifest from the
    // resolved parent media/manifest file and open the annotation's Canvas URI.
    $url = buildRecordOutputIiifUrl($baseUrl, array(
        'db' => $dbname,
        'iiif_image' => $resolvedIiifImageID
    ));

}elseif($idParam !== ''){

    if($idIsRecordID){

        // Numeric id case:
        // Treat id as a normal Heurist record ID and ask record_output.php to
        // generate a dynamic manifest from q=ids:{recordID}.
        $url = buildRecordOutputIiifUrl($baseUrl, array(
            'db' => $dbname,
            'q' => 'ids:'.$idParam
        ));

    }else{

        // Non-numeric id case:
        // Treat id as an uploaded file obfuscated ID. iiif_image is not a public
        // miradorViewer.php parameter anymore, but it remains the internal
        // record_output.php parameter for single-file dynamic manifests.
        $url = buildRecordOutputIiifUrl($baseUrl, array(
            'db' => $dbname,
            'iiif_image' => $idParam
        ));
        $hideThumbs = true;
    }

}elseif(@$_REQUEST['q']){

    // Query case:
    // Pass the Heurist query directly to record_output.php. This is the normal
    // dynamic manifest path for a resultset.
    $url = buildRecordOutputIiifUrl($baseUrl, array(
        'db' => $dbname,
        'q' => $_REQUEST['q']
    ));

}else{
    exit('Need to define manifest, id, q, url or preparedID');
}

if(@$_REQUEST['canvasUri']){
    // Viewer-only override. It selects the initial Canvas in Mirador and is not
    // forwarded to record_output.php.
    $canvasUri = $_REQUEST['canvasUri'];
}

if(strpos($url, 'hserv/controller/record_output.php')!==false){
    // Dynamic manifests should normally omit embedded AnnotationPage links.
    // The custom Mirador integration asks the Heurist annotation endpoint
    // directly, avoiding duplicate annotation loading paths.
    $url = appendQueryParam($url, 'omit_annotation_pages', '1');
}

$manifest_url = str_replace('&amp;','&',htmlspecialchars($url));

